-- Function to get export request summary
CREATE OR REPLACE FUNCTION get_export_request_summary(
    p_export_id UUID
) RETURNS TABLE(
    export_id UUID,
    export_type VARCHAR(50),
    export_format VARCHAR(20),
    status VARCHAR(20),
    requested_by VARCHAR(255),
    progress_percentage INTEGER,
    total_records INTEGER,
    processed_records INTEGER,
    estimated_completion TIMESTAMP WITH TIME ZONE,
    file_count BIGINT,
    total_file_size BIGINT
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        e.export_id,
        e.export_type,
        e.export_format,
        e.status,
        e.requested_by,
        e.progress_percentage,
        e.total_records,
        e.processed_records,
        e.estimated_completion,
        COALESCE(f.file_count, 0) as file_count,
        COALESCE(f.total_size, 0) as total_file_size
    FROM epic17_export_requests e
    LEFT JOIN (
        SELECT 
            export_id,
            COUNT(*) as file_count,
            SUM(file_size) as total_size
        FROM epic17_export_output_files 
        WHERE status = 'available'
        GROUP BY export_id
    ) f ON e.export_id = f.export_id
    WHERE e.export_id = p_export_id;
END;
$$ LANGUAGE plpgsql;

-- Function to calculate export performance metrics
CREATE OR REPLACE FUNCTION calculate_export_performance_metrics(
    p_time_window_hours INTEGER DEFAULT 24
) RETURNS TABLE(
    total_exports BIGINT,
    completed_exports BIGINT,
    failed_exports BIGINT,
    success_rate DECIMAL(5,2),
    average_execution_time DECIMAL(10,2),
    total_data_exported BIGINT,
    most_used_format VARCHAR(20),
    most_used_type VARCHAR(50),
    peak_concurrent_exports INTEGER
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COUNT(*) as total_exports,
        COUNT(*) FILTER (WHERE status = 'completed') as completed_exports,
        COUNT(*) FILTER (WHERE status = 'failed') as failed_exports,
        CASE 
            WHEN COUNT(*) > 0 THEN 
                (COUNT(*) FILTER (WHERE status = 'completed')::DECIMAL / COUNT(*) * 100)::DECIMAL(5,2)
            ELSE 0::DECIMAL(5,2)
        END as success_rate,
        AVG(execution_time) FILTER (WHERE execution_time > 0) as average_execution_time,
        SUM(file_size) as total_data_exported,
        
        (SELECT export_format 
         FROM epic17_export_requests 
         WHERE requested_at >= NOW() - (p_time_window_hours || ' hours')::INTERVAL
         GROUP BY export_format 
         ORDER BY COUNT(*) DESC 
         LIMIT 1) as most_used_format,
         
        (SELECT export_type 
         FROM epic17_export_requests 
         WHERE requested_at >= NOW() - (p_time_window_hours || ' hours')::INTERVAL
         GROUP BY export_type 
         ORDER BY COUNT(*) DESC 
         LIMIT 1) as most_used_type,
         
        -- This is a simplified calculation for peak concurrent exports
        (SELECT MAX(concurrent_count)
         FROM (
             SELECT 
                 COUNT(*) as concurrent_count
             FROM epic17_export_requests
             WHERE requested_at >= NOW() - (p_time_window_hours || ' hours')::INTERVAL
                 AND status IN ('preparing', 'exporting', 'processing', 'compressing', 'encrypting')
             GROUP BY DATE_TRUNC('hour', requested_at)
         ) subq) as peak_concurrent_exports
         
    FROM epic17_export_requests
    WHERE requested_at >= NOW() - (p_time_window_hours || ' hours')::INTERVAL;
END;
$$ LANGUAGE plpgsql;

-- Function to get scheduled export status
CREATE OR REPLACE FUNCTION get_scheduled_export_status() 
RETURNS TABLE(
    total_schedules BIGINT,
    active_schedules BIGINT,
    overdue_schedules BIGINT,
    successful_runs_today BIGINT,
    failed_runs_today BIGINT,
    next_scheduled_run TIMESTAMP WITH TIME ZONE
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        COUNT(*) as total_schedules,
        COUNT(*) FILTER (WHERE enabled = TRUE) as active_schedules,
        COUNT(*) FILTER (WHERE enabled = TRUE AND next_run_at < NOW()) as overdue_schedules,
        
        (SELECT COUNT(*) 
         FROM epic17_export_execution_history 
         WHERE execution_type = 'scheduled' 
             AND started_at >= CURRENT_DATE 
             AND status = 'completed') as successful_runs_today,
             
        (SELECT COUNT(*) 
         FROM epic17_export_execution_history 
         WHERE execution_type = 'scheduled' 
             AND started_at >= CURRENT_DATE 
             AND status = 'failed') as failed_runs_today,
             
        MIN(next_run_at) FILTER (WHERE enabled = TRUE AND next_run_at > NOW()) as next_scheduled_run
        
    FROM epic17_scheduled_exports;
END;
$$ LANGUAGE plpgsql;

-- Function to cleanup expired export files and requests
CREATE OR REPLACE FUNCTION cleanup_expired_exports() RETURNS INTEGER AS $$
DECLARE
    expired_requests INTEGER := 0;
    expired_files INTEGER := 0;
    total_cleaned INTEGER := 0;
BEGIN
    -- Update expired requests
    UPDATE epic17_export_requests 
    SET status = 'expired', updated_at = NOW()
    WHERE status NOT IN ('completed', 'failed', 'cancelled', 'expired')
        AND expires_at IS NOT NULL 
        AND expires_at <= NOW();
    
    GET DIAGNOSTICS expired_requests = ROW_COUNT;
    
    -- Mark output files as deleted for expired requests
    UPDATE epic17_export_output_files 
    SET status = 'deleted', deleted_at = NOW()
    WHERE export_id IN (
        SELECT export_id 
        FROM epic17_export_requests 
        WHERE status = 'expired'
    ) AND status = 'available';
    
    GET DIAGNOSTICS expired_files = ROW_COUNT;
    
    total_cleaned := expired_requests + expired_files;
    
    -- Log cleanup operation
    INSERT INTO epic17_admin_tool_usage (
        usage_id, tool_name, action, used_by, records_affected, success
    ) VALUES (
        gen_random_uuid(), 'export_service', 'cleanup_expired', 'system', total_cleaned, true
    );
    
    RETURN total_cleaned;
END;
$$ LANGUAGE plpgsql;

-- Function to apply redaction rules to exported data
CREATE OR REPLACE FUNCTION apply_redaction_rules(
    p_data JSONB,
    p_export_type VARCHAR(50),
    p_user_roles VARCHAR[] DEFAULT ARRAY[]::VARCHAR[]
) RETURNS JSONB AS $$
DECLARE
    rule RECORD;
    redacted_data JSONB := p_data;
    field_value TEXT;
BEGIN
    -- Get applicable redaction rules
    FOR rule IN
        SELECT * FROM epic17_export_redaction_rules
        WHERE enabled = TRUE
            AND (
                applies_to_export_types = '[]'::jsonb OR 
                applies_to_export_types ? p_export_type
            )
            AND (
                applies_to_user_roles = '[]'::jsonb OR 
                applies_to_user_roles ?| p_user_roles
            )
        ORDER BY priority ASC
    LOOP
        -- Check if field exists in data
        IF redacted_data ? rule.field_name THEN
            field_value := redacted_data ->> rule.field_name;
            
            -- Apply redaction based on type
            CASE rule.redaction_type
                WHEN 'mask' THEN
                    redacted_data := jsonb_set(
                        redacted_data, 
                        ('{' || rule.field_name || '}')::text[], 
                        to_jsonb(COALESCE(rule.replacement_value, '***MASKED***'))
                    );
                    
                WHEN 'remove' THEN
                    redacted_data := redacted_data - rule.field_name;
                    
                WHEN 'hash' THEN
                    redacted_data := jsonb_set(
                        redacted_data, 
                        ('{' || rule.field_name || '}')::text[], 
                        to_jsonb(encode(digest(field_value, 'sha256'), 'hex'))
                    );
                    
                WHEN 'anonymize' THEN
                    redacted_data := jsonb_set(
                        redacted_data, 
                        ('{' || rule.field_name || '}')::text[], 
                        to_jsonb(COALESCE(rule.replacement_value, 'ANONYMIZED'))
                    );
            END CASE;
            
            -- Update rule usage statistics
            UPDATE epic17_export_redaction_rules
            SET 
                usage_count = usage_count + 1,
                last_used_at = NOW()
            WHERE rule_id = rule.rule_id;
        END IF;
    END LOOP;
    
    RETURN redacted_data;
END;
$$ LANGUAGE plpgsql;

