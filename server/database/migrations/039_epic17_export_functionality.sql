-- Create comprehensive export dashboard view
CREATE VIEW epic17_export_dashboard AS
SELECT 
    -- Current activity
    (SELECT COUNT(*) FROM epic17_export_requests WHERE status IN ('pending', 'queued', 'preparing', 'exporting', 'processing')) as active_exports,
    (SELECT COUNT(*) FROM epic17_export_requests WHERE requested_at >= NOW() - INTERVAL '24 hours') as exports_today,
    
    -- Success metrics (last 7 days)
    (SELECT COUNT(*) FROM epic17_export_requests WHERE status = 'completed' AND completed_at >= NOW() - INTERVAL '7 days') as completed_last_week,
    (SELECT COUNT(*) FROM epic17_export_requests WHERE status = 'failed' AND requested_at >= NOW() - INTERVAL '7 days') as failed_last_week,
    
    -- Performance metrics
    (SELECT AVG(execution_time) FROM epic17_export_requests WHERE status = 'completed' AND completed_at >= NOW() - INTERVAL '24 hours') as avg_execution_time_today,
    (SELECT SUM(file_size) FROM epic17_export_requests WHERE status = 'completed' AND completed_at >= NOW() - INTERVAL '24 hours') as data_exported_today,
    
    -- File management
    (SELECT COUNT(*) FROM epic17_export_output_files WHERE status = 'available') as available_files,
    (SELECT SUM(file_size) FROM epic17_export_output_files WHERE status = 'available') as total_available_file_size,
    
    -- Scheduled exports
    (SELECT COUNT(*) FROM epic17_scheduled_exports WHERE enabled = TRUE) as active_schedules,
    (SELECT COUNT(*) FROM epic17_scheduled_exports WHERE enabled = TRUE AND next_run_at <= NOW() + INTERVAL '1 hour') as due_soon_schedules,
    
    -- Templates and redaction
    (SELECT COUNT(*) FROM epic17_export_templates WHERE is_active = TRUE) as active_templates,
    (SELECT COUNT(*) FROM epic17_export_redaction_rules WHERE enabled = TRUE) as active_redaction_rules,
    
    -- Notifications
    (SELECT COUNT(*) FROM epic17_export_notifications WHERE acknowledged = FALSE AND expires_at > NOW()) as unacknowledged_notifications,
    (SELECT COUNT(*) FROM epic17_export_notifications WHERE notification_type = 'failure' AND sent_at >= NOW() - INTERVAL '24 hours') as failure_notifications_today;

